    check(all(hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == digest for path, digest in files.items()), f'All {len(files)} captured application files unchanged')
    result = {'passed': len(checks), 'checks': checks, 'browser': browser.version, 'engine': 'headless Microsoft Edge', 'prototype_sha256': hashlib.sha256(HTML.read_bytes()).hexdigest(), 'screenshots': {name: hashlib.sha256((IMAGES / name).read_bytes()).hexdigest() for name in shots}, 'layout': layout, 'application_files_preserved': len(files), 'network_requests': [u for u in requests if not u.startswith('file:')], 'errors': errors}
    (OUT / 'results.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    print(json.dumps({k: result[k] for k in ['passed', 'browser', 'prototype_sha256', 'application_files_preserved', 'layout']}, indent=2))
    context.close()
    browser.close()
