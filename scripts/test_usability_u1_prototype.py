    check(page.locator('.sidebar button:enabled').count() == 0 and page.locator('#entry-form').count() == 0, 'Uncertain state pauses editing and navigation')
    capture('uncertain-1366.png')
    action('recover')
    page.wait_for_function('() => demoSnapshot().recoveryCalls === 1')
    check(snap()['view'] == 'uncertain' and snap()['postKey'] == key, 'Failed result check keeps the same recovery identity')
    tools()
