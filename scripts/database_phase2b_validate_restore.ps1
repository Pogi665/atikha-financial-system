function Assert-P2BPin([string]$Path,[string]$Hash){
    Assert-ContextDirectories ([IO.Path]::GetDirectoryName($Path))
    $item=Get-Item -LiteralPath $Path -Force
    if($item.PSIsContainer -or ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -or (Get-FileHash -LiteralPath $Path).Hash -ne $Hash){throw 'Pinned input/tool drift or unsafe path. Stop.'}
}
function Assert-P2BSourceManifest([string]$Manifest,[string]$Workspace){
    $spec=[IO.File]::ReadAllText($Manifest)|ConvertFrom-Json
    if($spec.Format -ne 'phase2b-readonly-source-v1' -or $spec.Files.Count -lt 10){throw 'Source manifest incomplete.'}
    foreach($f in $spec.Files){
        if($f.Path -notmatch '^(includes/[a-zA-Z0-9_]+\.php|scripts/database_phase2b_probe\.php)$'){throw 'Unexpected source manifest path.'}
        Assert-P2BPin (Join-Path $Workspace $f.Path) $f.SHA256
    }
}
function Assert-P2BProtected([object[]]$Trees){
    foreach($tree in $Trees){
        Assert-ContextDirectories $tree.Path
        $actual=Get-CheckTree $tree.Path
        if($actual.TreeSHA256 -ne $tree.Hash -or $actual.FileCount -ne $tree.Count -or
            @($actual.Entries|Where-Object{$_.Kind -eq 'F' -and [IO.Path]::GetExtension($_.Path) -ieq '.isl'}).Count){throw 'Protected source tree differs or has an external link.'}
    }
}
function Assert-P2BReport([object]$Report){
