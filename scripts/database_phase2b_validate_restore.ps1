        $script:probe,"--root=$($Context.Root)","--pid=$($Context.Process.Id)","--output=$output","--uploads=$script:uploads")
    $run=Invoke-BoundedCheck $script:php $argsProbe $Context.Root (Join-Path $Context.Logs 'probe.stdout.log') (Join-Path $Context.Logs 'probe.stderr.log') 180000
    Write-CheckJson (Join-Path $Context.Logs 'probe-result.json') $run
    if($run.TimedOut -or $run.ExitCode -ne 0 -or [IO.File]::ReadAllText((Join-Path $Context.Logs 'probe.stderr.log')).Trim().Length){throw 'Isolated table/integrity/evidence probe needs review. Stop without repair.'}
