function Invoke-P2BInputClient([string]$Executable,[string[]]$Arguments,[string]$InputFile,[string]$WorkingDirectory,[string]$Stdout,[string]$Stderr,[int]$TimeoutMs=120000){
    if((Test-Path -LiteralPath $Stdout) -or (Test-Path -LiteralPath $Stderr)){throw 'Input-client logs already exist. No retry.'}
    $nativeArgs=@($Arguments|ForEach-Object{ConvertTo-ContextNativeArgument $_})
    $client=Start-Process -FilePath $Executable -ArgumentList $nativeArgs -WorkingDirectory $WorkingDirectory -WindowStyle Hidden -PassThru `
        -RedirectStandardInput $InputFile -RedirectStandardOutput $Stdout -RedirectStandardError $Stderr
    $null=$client.Handle
    $timedOut=-not $client.WaitForExit($TimeoutMs)
    if($timedOut){$client.Kill();if(-not $client.WaitForExit(5000)){throw 'Timed-out input client did not exit. Never kill the server.'}}
    $client.WaitForExit()
    if($null -eq $client.ExitCode){throw 'Input-client exit code is unavailable.'}
    [pscustomobject]@{ExitCode=[int]$client.ExitCode;TimedOut=$timedOut;ProcessId=$client.Id}
}
function Invoke-P2BImport([object]$Context,[string]$Export,[string]$ExpectedHash){
    Assert-P2BRestoreContext $Context
    Assert-P2BPin $Context.Ini $Context.IniHash
    Assert-P2BPin $Export $ExpectedHash
    Assert-P2Process $Context.Process $Context.Server $Context.Ini $Context.Ticks $Context.Target -RequireListener -EvidenceDirectory $Context.Logs
    # Identity includes exact datadir/PID file/read_only=1/events/logging off, not just a port.
    $sql='SELECT @@port,@@datadir,@@pid_file,VERSION(),@@global.read_only,@@global.innodb_force_recovery,@@global.event_scheduler,@@global.log_bin,@@global.general_log,@@global.slow_query_log;'
    Assert-P2Identity (Invoke-P2Sql $Context 'before-restore-identity' $sql) $Context.Root $Context.Process.Id
    $null=Invoke-P2Sql $Context 'drop-disposable-application-schema' 'DROP DATABASE `atikha_finance`;'
    $remaining=Invoke-P2Sql $Context 'empty-restore-schema' "SELECT COUNT(*) FROM information_schema.SCHEMATA WHERE SCHEMA_NAME='atikha_finance';"
    if($remaining.Trim() -ne '0'){throw 'Disposable application schema is not absent. No import.'}
    Assert-P2BPin $Export $ExpectedHash
    Assert-P2Process $Context.Process $Context.Server $Context.Ini $Context.Ticks $Context.Target -RequireListener -EvidenceDirectory $Context.Logs
    $out=Join-Path $Context.Logs 'import.stdout.log';$err=Join-Path $Context.Logs 'import.stderr.log'
    if((Test-Path -LiteralPath $out) -or (Test-Path -LiteralPath $err)){throw 'Import already attempted. No retry.'}
    Write-CheckJson (Join-Path $Context.Root 'import-attempt.json') ([ordered]@{At=(Get-Date).ToString('o');ExportSHA256=$ExpectedHash;Candidate=$Context.Root;Database='atikha_finance';WorkingDatabase=$false;NoForce=$true})
    $result=Invoke-P2BInputClient $Context.Mysql @(Get-P2BImportArguments) $Export $Context.Root $out $err 120000
    Write-CheckJson (Join-Path $Context.Logs 'import-result.json') $result
    if($result.TimedOut -or $result.ExitCode -ne 0 -or [IO.File]::ReadAllText($err).Trim().Length){throw 'Restore import failed or needs review. No force/retry.'}
    Assert-P2Process $Context.Process $Context.Server $Context.Ini $Context.Ticks $Context.Target -RequireListener -EvidenceDirectory $Context.Logs
    Assert-P2BPin $Export $ExpectedHash
}
