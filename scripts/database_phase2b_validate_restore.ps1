        $null -eq $Report.snapshot -or $null -eq $Report.evidence){throw 'Inspection did not fully pass. See private report.'}
}
function Assert-P2BEqual([object]$First,[object]$Second){
    # Both are generated by the same pinned probe, with deterministic ordering and string/null values.
