}
function Close-P2BCopy {
    if($null -eq $script:activeProcess){return}
    if($null -eq $script:activeContext){throw 'Candidate identity capture incomplete. Do not stop/force it automatically.'}
    $shutdown=Stop-P2Gracefully $script:activeContext $script:admin
    Write-CheckJson (Join-Path $script:activeContext.Root 'shutdown-result.json') $shutdown
    if($shutdown.State -ne 'gracefully-stopped'){throw 'Candidate did not complete a verified graceful stop.'}
    $script:activeContext.Target.Dispose()
    Assert-CheckOffline
    Write-CheckJson (Join-Path $script:activeContext.Root 'candidate-after.json') (Get-CheckTree (Join-Path $script:activeContext.Root 'data'))
    $script:activeProcess=$null;$script:activeContext=$null
}

